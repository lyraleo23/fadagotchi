const pixieCache = {};
function pixieSprite(stage, face, up) {
  const key = stage + face + up;
  if (pixieCache[key]) return pixieCache[key];
  const def = SPR[stage];
  const rows = def.base.slice();
  const f = def.faces[face];
  if (f) for (const i in f) rows[i] = f[i];
  const wing = up ? def.wingsUp : def.wingsDown;
  const out = rows.map((r, y) => {
    const wr = wing[y] || '';
    let s = '';
    for (let x = 0; x < r.length; x++) s += (r[x] === '#' || wr[x] === '#') ? '#' : '.';
    return s;
  });
  return (pixieCache[key] = S(out));
}

