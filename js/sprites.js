function S(rows) {
  const h = rows.length, w = Math.max(...rows.map(r => r.length));
  const d = new Uint8Array(w * h);
  rows.forEach((r, y) => { for (let x = 0; x < r.length; x++) if (r[x] === '#') d[y * w + x] = 1; });
  return { w, h, d };
}
